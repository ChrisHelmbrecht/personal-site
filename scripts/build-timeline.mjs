// Rebuilds timeline-data.js from the photo folders.
//   assets/timeline/1999/cover.jpg        -> cover of that year (any file whose name contains "cover")
//   assets/timeline/1999/01.jpg, 02.jpg   -> gallery, in filename order
//   assets/timeline/1999/label.txt        -> optional one-line caption ("New York")
// Run: node scripts/build-timeline.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = "assets/timeline";
const isImage = f => /\.(jpe?g|png|webp|avif)$/i.test(f);

const years = readdirSync(root, { withFileTypes: true })
  .filter(d => d.isDirectory() && /^\d{4}$/.test(d.name))
  .map(d => {
    const dir = join(root, d.name);
    const files = readdirSync(dir).filter(isImage).sort();
    const cover = files.find(f => /cover/i.test(f)) || files[0] || "";
    const labelFile = join(dir, "label.txt");
    return {
      year: Number(d.name),
      label: existsSync(labelFile) ? readFileSync(labelFile, "utf8").trim() : "",
      cover: cover ? `${root}/${d.name}/${cover}` : "",
      images: files.map(f => `${root}/${d.name}/${f}`),
    };
  })
  .sort((a, b) => b.year - a.year);

writeFileSync(
  "timeline-data.js",
  `// Generated by scripts/build-timeline.mjs. Do not edit by hand.\nwindow.TIMELINE = ${JSON.stringify(years, null, 2)};\n`
);
console.log(`timeline-data.js: ${years.length} years, ${years.reduce((n, y) => n + y.images.length, 0)} photos`);
